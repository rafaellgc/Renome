const dicts: Record<Lang, Dict> = { pt, en, es };

export const LANG_NAMES: Record<Lang, string> = { pt: "Português", en: "English", es: "Español" };
export const LOCALES: Record<Lang, string> = { pt: "pt-BR", en: "en-US", es: "es-ES" };
/** Modifier key name for shortcuts. */
export const MOD = navigator.userAgent.includes("Mac") ? "⌘" : "Ctrl";

/** Translates a key, replacing `{var}` with the given values. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = dicts[settings.lang]?.[key] ?? pt[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, v) => (v in vars ? String(vars[v]) : m));
}

/** Translates an error from Rust in the form `code` or `code: detail`. */
export function tError(raw: unknown): string {
  const s = String(raw);
  const [code, ...rest] = s.split(": ");
  if (code in pt) {
    const detail = rest.join(": ");
    return t(code as Key) + (detail ? `: ${detail}` : "");
  }
  return s;
}
